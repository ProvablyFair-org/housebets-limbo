#!/usr/bin/env node
// Generates verify.js: tests/verify.ts and everything it imports in one plain-JavaScript file, so `node verify.js` runs the
// whole suite on Node 22 with nothing installed and no TypeScript flags. Built with Bun's bundler (auditor tooling only;
// the output needs nothing but Node). verify.js reads data/, evidence/ and outputs/ from the folder it sits in.
// the header carries the digest of the sources it was built from (tests/verify.ts + src/*.ts,
// sorted by path: sha256 of "path\nsha256(bytes)\n" per file); verify recomputes it from disk and fails the artifacts check
// (-27) when the bundle is stale, so verify.js and tests/verify.ts cannot drift.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Stale-bundle guard, exit 4 (14 Oct 2026, exit codes harmonised across the 11 HouseBets packages; same shape as plinko's
// scripts/build-standalone.mjs): the sha256 of every source the bundle is built from (tests/verify.ts, src/*.ts and, where it
// exists, scripts/fingerprint.mjs) is embedded right below the header; verify.js re-derives them from disk before anything else
// runs and exits 4, with no verdict, when one differs or is missing. The -27 check's own bundle comparison is unchanged.
import { readdirSync as __rdSync, existsSync as __exSync } from 'node:fs';
import { createHash as __mkHash } from 'node:crypto';
function staleGuard(root) {
  const files = ['tests/verify.ts', ...__rdSync(join(root, 'src')).filter((f) => f.endsWith('.ts')).sort().map((f) => `src/${f}`),
    ...(__exSync(join(root, 'scripts', 'fingerprint.mjs')) ? ['scripts/fingerprint.mjs'] : [])];
  const sources = Object.fromEntries(files.map((p) => [p, __mkHash('sha256').update(readFileSync(join(root, p))).digest('hex')]));
  return `import { readFileSync as __pfRead, existsSync as __pfExists } from 'node:fs';
import { createHash as __pfHash } from 'node:crypto';
import { join as __pfJoin, dirname as __pfDir } from 'node:path';
import { fileURLToPath as __pfPath } from 'node:url';
const __pfSources = ${JSON.stringify(sources, null, 2)};
{
  const root = __pfDir(__pfPath(import.meta.url));
  const stale = Object.entries(__pfSources).filter(([p, h]) => !__pfExists(__pfJoin(root, p)) || __pfHash('sha256').update(__pfRead(__pfJoin(root, p))).digest('hex') !== h).map(([p]) => p);
  if (stale.length) { console.log('STALE STANDALONE BUNDLE: verify.js was not built from the sources in this folder (' + stale.join(', ') + ') — run npm run build:standalone; no verdict'); process.exit(4); }
}
`;
}
const sha = (b) => createHash('sha256').update(b).digest('hex');
export function sourcesSha256(root) {
  const files = ['tests/verify.ts', ...readdirSync(join(root, 'src')).filter((f) => f.endsWith('.ts')).map((f) => `src/${f}`)].sort();
  return sha(files.map((f) => `${f}\n${sha(readFileSync(join(root, f)))}\n`).join(''));
}
/** The installed bun's version (`bun --version`), or null when bun is not installed. */
export function bunVersionOf() { const r = spawnSync('bun', ['--version'], { encoding: 'utf8' }); return r.status === 0 ? r.stdout.trim() : null; }
/** The bun version a verify.js header records, or null (a bundle built before the version was recorded). */
export const bundledWith = (text) => (/^ \* Bundled with bun (\S+)$/m.exec(text) || [])[1] ?? null;
if (process.argv[1] && /build-standalone\.mjs$/.test(process.argv[1])) {
  const r = spawnSync('bun', ['build', 'tests/verify.ts', '--target=node', '--format=esm', '--outfile=verify.js.tmp'], { cwd: ROOT, encoding: 'utf8' });
  if (r.status !== 0) { console.error(r.stdout, r.stderr); process.exit(1); }
  const body = readFileSync(join(ROOT, 'verify.js.tmp'), 'utf8');
  // the bundler's version is recorded in the header (and, from it, in RELEASE-MANIFEST.json): another bun version can name
  // local variables differently, so a byte comparison of a rebuild needs the same bun
  const bunVersion = bunVersionOf();
  const header = `/**\n * STANDALONE VERIFIER — generated by scripts/build-standalone.mjs from tests/verify.ts, do not edit.\n *\n *     node verify.js\n *\n * Node 22, nothing to install. Source sha256 of tests/verify.ts: ${sha(readFileSync(join(ROOT, 'tests', 'verify.ts')))}\n * Sources sha256 (tests/verify.ts + src/*.ts): ${sourcesSha256(ROOT)}\n * Bundled with bun ${bunVersion}\n */\n`;
  const guarded = header + staleGuard(ROOT) + body;
  writeFileSync(join(ROOT, 'verify.js'), guarded);
  spawnSync('rm', ['-f', join(ROOT, 'verify.js.tmp')]);
  console.log(`wrote verify.js (${guarded.length} chars, stale guard: exit 4)`);
}
